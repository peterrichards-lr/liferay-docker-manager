#!/usr/bin/env python3
"""Generate the per-site reclaim matrix from source (LDM-#2151).

The matrix was stated three times -- in the code, in
`.agents/skills/ldm-architecture/SKILL.md` and in
`docs/explanation/permissions-and-reclaim.md` -- and nothing kept them in step.
LDM-#2143 was the result: a reader trusted a table that no longer matched the
path their command took.

This reads the reclaim loops by AST (`reclaim_sites.py`, the same parser the
test uses) and writes the matrix between `<!-- RECLAIM_TABLE_START -->` and
`<!-- RECLAIM_TABLE_END -->` in BOTH files. Both, rather than a shared snippet
included by mkdocs, because the skill is read raw by an agent and an unexpanded
include directive would be worse than the duplication.

Everything outside the markers is editorial and hand-written: the gates, the
"via `osgi`" coverage, the `routes` special case, and the `created by` and
snapshot columns, which derive from other code.

    scripts/sync_reclaim_table.py           rewrite both blocks in place
    scripts/sync_reclaim_table.py --check   exit 1 if either block is stale

Exit codes: 0 in sync (or rewritten), 1 drift under --check, 2 a configuration
error -- an unreadable reclaim loop, or missing/duplicated/reversed markers.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from reclaim_sites import PROJECT_ROOT, ReclaimParseError, site_columns

START_MARKER = "<!-- RECLAIM_TABLE_START -->"
END_MARKER = "<!-- RECLAIM_TABLE_END -->"

#: Every document carrying the generated block, relative to the project root.
TARGETS: tuple[str, ...] = (
    ".agents/skills/ldm-architecture/SKILL.md",
    "docs/explanation/permissions-and-reclaim.md",
)

EXIT_DRIFT = 1
EXIT_CONFIG = 2


class MarkerError(Exception):
    """The markers in a target are missing, duplicated or out of order."""


def render_table(columns: list[tuple[str, list[str]]]) -> str:
    """The matrix: one row per path key, in order of first appearance."""
    keys: list[str] = []
    for _, entries in columns:
        for key in entries:
            if key not in keys:
                keys.append(key)
    lines = [
        "| path key | " + " | ".join(h for h, _ in columns) + " |",
        "|---|" + "---|" * len(columns),
    ]
    for key in keys:
        cells = ["yes" if key in entries else "no" for _, entries in columns]
        lines.append(f"| `{key}` | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_block(table: str) -> str:
    return (
        f"{START_MARKER}\n"
        "<!-- Generated by scripts/sync_reclaim_table.py from the reclaim loops "
        "in source. Do not edit by hand. -->\n\n"
        f"{table}\n\n"
        f"{END_MARKER}"
    )


def splice(text: str, block: str, label: str) -> str:
    """Replace the marked region of `text` with `block`."""
    starts = text.count(START_MARKER)
    ends = text.count(END_MARKER)
    if starts != 1 or ends != 1:
        raise MarkerError(
            f"{label}: expected exactly one {START_MARKER} and one "
            f"{END_MARKER}, found {starts} and {ends}."
        )
    start = text.index(START_MARKER)
    end = text.index(END_MARKER)
    if end < start:
        raise MarkerError(f"{label}: {END_MARKER} comes before {START_MARKER}.")
    return text[:start] + block + text[end + len(END_MARKER) :]


def sync(root: Path, check: bool) -> int:
    try:
        block = render_block(render_table(site_columns(root)))
        updates: list[tuple[Path, str, str]] = []
        for rel in TARGETS:
            path = root / rel
            if not path.is_file():
                raise MarkerError(f"{rel}: file not found.")
            old = path.read_text(encoding="utf-8")
            updates.append((path, old, splice(old, block, rel)))
    except (ReclaimParseError, MarkerError) as e:
        print(f"sync_reclaim_table: {e}", file=sys.stderr)
        return EXIT_CONFIG

    stale = [(p, old, new) for p, old, new in updates if old != new]
    if check:
        for path, old, new in stale:
            rel = path.relative_to(root).as_posix()
            print(
                f"{rel}: the reclaim table is out of date with the source. "
                f"Run scripts/sync_reclaim_table.py.",
                file=sys.stderr,
            )
            sys.stderr.writelines(
                difflib.unified_diff(
                    old.splitlines(keepends=True),
                    new.splitlines(keepends=True),
                    fromfile=f"{rel} (committed)",
                    tofile=f"{rel} (generated)",
                )
            )
        return EXIT_DRIFT if stale else 0

    for path, _, new in stale:
        path.write_text(new, encoding="utf-8")
        print(f"Updated {path.relative_to(root).as_posix()}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="sync_reclaim_table.py",
        description=(
            "Regenerate the per-site reclaim matrix from the reclaim loops in "
            "source, in every document that carries it."
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Change nothing; exit 1 if any generated table is out of date.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=PROJECT_ROOT,
        help=argparse.SUPPRESS,  # tests point this at a copy of the tree
    )
    args = parser.parse_args(argv)
    return sync(args.root, args.check)


if __name__ == "__main__":
    sys.exit(main())
